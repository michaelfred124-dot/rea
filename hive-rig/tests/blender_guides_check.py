"""Check guide editing and rebuilding in real Blender.

Builds a generated rig, moves a guide, paints a weight, adds fingers and a tail
through the Hive tools, rebuilds, and checks the result. The script must have
been generated by a hive-rig build that is still on disk (it calls it back).

    python blender_guides_check.py <name>_blender.py
"""

import json
import os
import runpy
import sys

import bpy
from mathutils import Vector

script = (sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else sys.argv[1:])[0]

bpy.ops.wm.read_factory_settings(use_empty=True)
saved_argv = sys.argv
sys.argv = ["blender"]
hive = runpy.run_path(script, run_name="__main__")
sys.argv = saved_argv

failures = []


def check(cond, msg):
    print(("ok: " if cond else "FAIL: ") + msg)
    if not cond:
        failures.append(msg)


def the_rig():
    return next(o for o in bpy.data.objects if o.type == "ARMATURE")


rig = the_rig()
geo = hive["rig_mesh"](rig)
name = rig["hive_name"]
check(hasattr(bpy.types, "HIVE_PT_panel"), "the Hive tab is registered")

# Running the script again in the same file only brings the tab back.
sys.argv = ["blender"]
runpy.run_path(script, run_name="__main__")
sys.argv = saved_argv
check(len([o for o in bpy.data.objects if o.type == "ARMATURE"]) == 1, "re-running the script doesn't build a second rig")

# Edit guides: one empty per guide, rig hidden.
hive["show_guides"](rig)
guides = hive["guide_objects"](rig)
data = json.loads(rig["hive_guides"])
total = sum(len(c["guides"]) for c in data["components"])
check(len(guides) == total and total > 20, "edit guides puts out an empty for each of the %d guides" % total)
check(rig.hide_get(), "the rig is hidden while editing guides")

# Move the left elbow guide down and mirror it to the right.
elbow = next(o for o in guides if o["hive_component"] == "arm_l" and o["hive_guide"] == "elbow")
target = elbow.location + Vector((0.0, 0.04, -0.05))
elbow.location = target
bpy.context.view_layer.update()
hive["mirror_guides"](rig)
r_elbow = next(o for o in hive["guide_objects"](rig) if o["hive_component"] == "arm_r" and o["hive_guide"] == "elbow")
check(abs(r_elbow.location.x + target.x) < 1e-4 and abs(r_elbow.location.z - target.z) < 1e-4, "mirror copies the left elbow to the right")

# Paint a custom weight on a torso vertex: all on spine_02.
groups = {vg.name: vg for vg in geo.vertex_groups}
chest_v = min(
    (v for v in geo.data.vertices if abs(v.co.x) < 0.02 and v.co.y < 0),
    key=lambda v: abs(v.co.z - 1.15),
).index
for vg in geo.vertex_groups:
    vg.remove([chest_v])
groups["spine_02"].add([chest_v], 1.0, "REPLACE")

# Add fingers and a tail, then rebuild.
msg = hive["change_components"](rig, "add", "fingers")
check("index_l" in msg, "add fingers reports the new components (%s)" % msg)
hive["change_components"](rig, "add", "tail")
check(any(o["hive_component"] == "tail" for o in hive["guide_objects"](rig)), "tail guides appear")

rig = hive["rebuild"](rig, keep_weights=True)
geo = hive["rig_mesh"](rig)
bones = rig.data.bones
check(not hive["guide_objects"](rig) and not rig.hide_get(), "rebuild clears the guides and shows the rig")
check((bones["lowerarm_l"].head_local - target).length < 1e-4, "the rebuilt elbow sits on the moved guide")
check((bones["lowerarm_r"].head_local.x + target.x) < 1e-4, "the mirrored right elbow was rebuilt too")
for b in ("thumb_01_l", "index_03_r", "tail_05"):
    check(b in bones, "rebuilt rig has %s" % b)
check("index_01_l_ctrl" in rig.pose.bones and "tail_01_ctrl" in rig.pose.bones, "new components get controls")

w = {geo.vertex_groups[g.group].name: g.weight for g in geo.data.vertices[chest_v].groups if g.weight > 0}
check(w == {"spine_02": 1.0}, "the painted weight survives the rebuild (%s)" % w)
finger_weighted = sum(
    1 for v in geo.data.vertices if any(geo.vertex_groups[g.group].name.startswith("middle_") and g.weight > 0 for g in v.groups)
)
check(finger_weighted > 0, "new finger bones get automatic weights (%d vertices)" % finger_weighted)

# The rebuilt rig still works: a finger control bends the finger, the arm still reaches IK.
pb = rig.pose.bones
tip0 = (rig.matrix_world @ pb["index_03_l"].tail).copy()
pb["index_01_l_ctrl"].rotation_euler = (0.0, 0.0, 0.8)
bpy.context.view_layer.update()
tip1 = rig.matrix_world @ pb["index_03_l"].tail
check((tip1 - tip0).length > 0.01, "the finger control bends the finger")

check(os.path.isfile(os.path.join(rig["hive_dir"], name + ".guides.json")), "guides are saved next to the rig")

if failures:
    print("%d guide check(s) failed" % len(failures))
    sys.exit(1)
print("guide check passed")
