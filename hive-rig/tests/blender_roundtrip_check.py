"""Check that weights and shapes go to Blender natively and come back, in real Blender.

Builds a generated rig whose shapes have in-betweens, then checks:

* every hive-rig shape is a shape key per target (`<shape>_ib50`, then
  `<shape>`), with the same offsets, and every driver is a simple expression;
* a corrective shape with an in-between blends through it as its joint bends
  (the in-between fully on where its reader reaches the in-between's weight,
  the full shape at the end of the bend);
* an undriven shape with an in-between follows its slider on the armature;
* Send to Hive brings a repainted vertex, a resculpted shape key, a new shape
  key and a moved slider back into the .hive.json (and nothing else changes);
* Rebuild keeps them, in Blender and in the .hive.json.

The script must have been generated by a hive-rig build still on disk (Send to
Hive and Rebuild call it back).

    python -I blender_roundtrip_check.py <name>_blender.py --corrective SHAPE CONTROL --slider SHAPE
"""

import json
import math
import os
import runpy
import sys

import bpy

args = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else sys.argv[1:]
script = args[0]


def opt(name, n=1):
    if name not in args:
        return None
    i = args.index(name)
    return args[i + 1 : i + 1 + n] if n > 1 else args[i + 1]


corrective = opt("--corrective", 2)
slider = opt("--slider")

failures = []


def check(cond, msg):
    print(("ok: " if cond else "FAIL: ") + msg)
    if not cond:
        failures.append(msg)


bpy.ops.wm.read_factory_settings(use_empty=True)
saved_argv = sys.argv
sys.argv = ["blender"]
hive = runpy.run_path(script, run_name="__main__")
sys.argv = saved_argv

rig = next(o for o in bpy.data.objects if o.type == "ARMATURE")
name = rig["hive_name"]
hive_path = os.path.join(rig["hive_dir"], name + ".hive.json")
data = json.load(open(hive_path))
shapes = {s["name"]: s for s in data["mesh"]["shapes"]}
geos = hive["rig_meshes"](rig)
geo = geos[0]
keys = geo.data.shape_keys.key_blocks


def evaluate(key):
    rig.update_tag()
    bpy.context.view_layer.update()
    dg = bpy.context.evaluated_depsgraph_get()
    return geo.data.shape_keys.evaluated_get(dg).key_blocks[key].value


# ------------------------------------------------------------------ native keys
with_ibs = [s for s in shapes.values() if s.get("inbetweens")]
check(with_ibs, "the rig has shapes with in-betweens (%s)" % ", ".join(s["name"] for s in with_ibs))
basis = [v.co.copy() for v in keys["Basis"].data]
for s in shapes.values():
    for key, _, vertices, offsets in hive["shape_targets"](s):
        if key not in keys:
            check(False, "shape key %s is there" % key)
            continue
        worst = 0.0
        for v, d in zip(vertices, offsets):
            got = keys[key].data[v].co - basis[v]
            want = hive["to_blender"](d)
            worst = max(worst, (got - want).length)
        check(worst < 1e-5, "shape key %s holds the offsets of %d vertices (worst %.2g m)" % (key, len(vertices), worst))
drivers = geo.data.shape_keys.animation_data.drivers if geo.data.shape_keys.animation_data else []
check(all(fc.driver.is_simple_expression for fc in drivers),
      "all %d shape key drivers are simple expressions (no Python auto-run needed)" % len(drivers))

# ------------------------------------------------------------------ a corrective through its in-between
if corrective:
    shape, control = corrective
    s = shapes[shape]
    reader = s["driver"]
    ib = s["inbetweens"][0]
    ib_key = hive["inbetween_name"](shape, ib["weight"])
    pb = rig.pose.bones[control]
    pb.rotation_mode = "XYZ"
    check(evaluate(shape) < 1e-3 and evaluate(ib_key) < 1e-3, "%s and %s are off at rest" % (shape, ib_key))
    best = (0.0, None)
    for axis in range(3):
        for sign in (1, -1):
            e = [0.0, 0.0, 0.0]
            e[axis] = sign * math.radians(reader["end"])
            pb.rotation_euler = e
            v = evaluate(shape)
            if v > best[0]:
                best = (v, (axis, sign))
    pb.rotation_euler = (0, 0, 0)
    value, how = best
    check(how is not None and value > 0.9,
          "bending %s fully turns %s on (%.3f)" % (control, shape, value))
    if how is not None:
        axis, sign = how
        e = [0.0, 0.0, 0.0]
        e[axis] = sign * math.radians(reader["end"])
        pb.rotation_euler = e
        check(evaluate(ib_key) < 0.1, "at the full bend %s is off (%.3f)" % (ib_key, evaluate(ib_key)))
        # Find the bend where the in-between is fully on: it should be near
        # the reader's angle for the in-between's weight.
        peak = (0.0, 0.0)
        for step in range(0, 91):
            angle = reader["end"] * step / 90.0
            e[axis] = sign * math.radians(angle)
            pb.rotation_euler = e
            v = evaluate(ib_key)
            if v > peak[0]:
                peak = (v, angle)
        expected = reader["start"] + ib["weight"] * (reader["end"] - reader["start"])
        check(peak[0] > 0.9, "%s comes fully on part way through the bend (%.3f)" % (ib_key, peak[0]))
        check(abs(peak[1] - expected) < 0.15 * reader["end"],
              "%s peaks at %.0f degrees of bend, near the %.0f its weight %.2f asks for" % (ib_key, peak[1], expected, ib["weight"]))
        e[axis] = sign * math.radians(peak[1])
        pb.rotation_euler = e
        check(evaluate(shape) < 0.15, "where %s peaks, %s is nearly off (%.3f)" % (ib_key, shape, evaluate(shape)))
    pb.rotation_euler = (0, 0, 0)

# ------------------------------------------------------------------ an undriven shape's slider
if slider:
    s = shapes[slider]
    prop = hive["shape_property"](slider)
    check(prop in rig.keys(), "the armature has a %s slider" % prop)
    ib = s["inbetweens"][0]
    ib_key = hive["inbetween_name"](slider, ib["weight"])
    rig[prop] = ib["weight"]
    check(abs(evaluate(ib_key) - 1.0) < 1e-3 and evaluate(slider) < 1e-3,
          "the slider at %.2f shows only %s" % (ib["weight"], ib_key))
    rig[prop] = 1.0
    check(abs(evaluate(slider) - 1.0) < 1e-3 and evaluate(ib_key) < 1e-3, "the slider at 1 shows only %s" % slider)
    rig[prop] = 0.0
    check(evaluate(slider) < 1e-3 and evaluate(ib_key) < 1e-3, "the slider at 0 shows neither")

# ------------------------------------------------------------------ edit here, send back
start = geo.get("hive_first_vertex", 0)
deform = [b["name"] for b in data["skeleton"]["bones"] if b["deform"]]
v_paint = len(geo.data.vertices) // 3
bone = deform[len(deform) // 2]
groups = {vg.name: vg for vg in geo.vertex_groups}
for g in geo.data.vertices[v_paint].groups:
    geo.vertex_groups[g.group].remove([v_paint])
groups[bone].add([v_paint], 1.0, "REPLACE")

sculpt_shape = slider or next(iter(shapes))
v_sculpt = shapes[sculpt_shape]["vertices"][0]
before = shapes[sculpt_shape]["offsets"][0]
keys[sculpt_shape].data[v_sculpt - start].co.z += 0.01  # Blender's Z is hive-rig's Y
new_key = geo.shape_key_add(name="from_blender", from_mix=False)
new_key.data[5].co.x += 0.02  # hive-rig's X
new_key.value = 0.3
if slider:
    rig[hive["shape_property"](slider)] = 0.6

said = hive["send_edits"](rig)
print("send to hive: " + said)
check("1 of" in said, "Send to Hive changes exactly the repainted vertex (%s)" % said)
after = json.load(open(hive_path))
skin = after["skin"]
names = [b["name"] for b in after["skeleton"]["bones"]]
got = {names[j]: w for j, w in zip(skin["joints"][start + v_paint], skin["weights"][start + v_paint]) if w > 0}
check(got == {bone: 1.0}, "vertex %d is all %s in the .hive.json (%s)" % (start + v_paint, bone, got))
others = sum(1 for v in range(len(skin["joints"])) if v != start + v_paint
             and (skin["joints"][v], skin["weights"][v]) != (data["skin"]["joints"][v], data["skin"]["weights"][v]))
check(others == 0, "no other vertex's weights changed (%d did)" % others)
shapes_after = {s["name"]: s for s in after["mesh"]["shapes"]}
s = shapes_after[sculpt_shape]
k = s["vertices"].index(v_sculpt)
check(abs(s["offsets"][k][1] - before[1] - 0.01) < 1e-5, "the resculpted %s moved its vertex up 1 cm" % sculpt_shape)
check(len(s.get("inbetweens", [])) == len(shapes[sculpt_shape].get("inbetweens", [])),
      "%s keeps its in-betweens" % sculpt_shape)
if slider:
    check(abs(s["weight"] - 0.6) < 1e-5, "%s's slider came back at 0.6 (%.3f)" % (slider, s["weight"]))
n = shapes_after.get("from_blender")
check(n is not None and n["vertices"] == [start + 5] and abs(n["offsets"][0][0] - 0.02) < 1e-5
      and abs(n.get("weight", 0) - 0.3) < 1e-5, "the new shape key came back as a shape at 0.3")
if corrective:
    c = shapes_after[corrective[0]]
    check(c.get("driver") == shapes[corrective[0]]["driver"], "%s keeps its pose reader" % corrective[0])
    check(c["inbetweens"][0]["vertices"] == shapes[corrective[0]]["inbetweens"][0]["vertices"],
          "%s's in-between came back unchanged" % corrective[0])

# ------------------------------------------------------------------ rebuild keeps them
rig = hive["rebuild"](rig, True)
geo = hive["rig_meshes"](rig)[0]
after = json.load(open(hive_path))
skin = after["skin"]
names = [b["name"] for b in after["skeleton"]["bones"]]
got = {names[j]: w for j, w in zip(skin["joints"][start + v_paint], skin["weights"][start + v_paint]) if w > 0}
check(got == {bone: 1.0}, "after Rebuild the .hive.json keeps the painted vertex (%s)" % got)
here = {geo.vertex_groups[g.group].name: g.weight for g in geo.data.vertices[v_paint].groups if g.weight > 0}
check(here == {bone: 1.0}, "after Rebuild Blender keeps the painted vertex (%s)" % here)
keys = geo.data.shape_keys.key_blocks
check("from_blender" in keys and sculpt_shape in keys, "after Rebuild the shape keys are there")
moved = keys[sculpt_shape].data[v_sculpt - start].co - keys["Basis"].data[v_sculpt - start].co
check(abs(moved.z - before[1] - 0.01) < 1e-5, "after Rebuild %s keeps the sculpt" % sculpt_shape)

if failures:
    print("ROUND TRIP CHECK FAILED (%d)" % len(failures))
    sys.exit(1)
print("round trip check passed")
